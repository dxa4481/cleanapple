# Character order in ROM: @ A-Z [ \ ] ^ _ (space) ! " # ... ?
ROM_ORDER = '@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_ !"#$%&\'()*+,-./0123456789:;<=>?'


def make_chargen_rom():
    """Generate the character generator ROM."""
    rom = bytearray(2048)
    
    # Fill 4 banks
    for bank in range(4):
        bank_offset = bank * 512
        high_bit = 0x80 if (bank == 1 or bank == 3) else 0x00
        
        for i, char in enumerate(ROM_ORDER):
            if char in CHAR_PATTERNS:
                pattern = CHAR_PATTERNS[char]
                for row in range(8):
                    rom[bank_offset + i * 8 + row] = pattern[row] | high_bit
            else:
                # Blank character if not defined
                for row in range(8):
                    rom[bank_offset + i * 8 + row] = high_bit
    
    return rom


def main():
    """Generate the ROM and write to file."""
    rom = make_chargen_rom()
    
    output_path = "/workspace/cleanroom_roms/chargen.bin"
    with open(output_path, "wb") as f:
        f.write(rom)
    
    print(f"Generated {output_path}")
    print(f"Size: {len(rom)} bytes")
    
    # Verify structure
    print("\nVerifying structure:")
    print(f"  Bank 0 (normal): starts at $000")
    print(f"  Bank 1 (inverse): starts at $200")
    print(f"  Bank 2 (normal copy): starts at $400")
    print(f"  Bank 3 (inverse copy): starts at $600")
    
    # Show sample characters
    print("\nSample characters (Bank 0):")
    for char in ['@', 'A', ' ', '0']:
        idx = ROM_ORDER.index(char)
        print(f"\n  '{char}' (index {idx}):")
        for row in range(8):
            b = rom[idx * 8 + row]
            line = ""
            for bit in range(7):
                if b & (1 << bit):
                    line += "█"
                else:
                    line += " "
            print(f"    {line}")


if __name__ == "__main__":
    main()
